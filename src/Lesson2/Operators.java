package Lesson2;

public class Operators {
    public static void main(String[] args) {
        int a = 12;
        int b = 2;
        int resultOfAddiction = a + b;
        System.out.println(resultOfAddiction); // a, b, operands, + is operator
        int resultOfSubtraction = a - b;
        System.out.println(resultOfSubtraction);
        int c = 5;
        int resultOfModulus = a % c;
        System.out.println(resultOfModulus);
    }
}
